let ts3ClientQuery: TS3ClientQuery | null = null;
const getTs3Client = (): TS3ClientQuery => {
  // @ts-ignore
  const apiKey: string = settingsStore.get("config.ts3ClientQueryApiKey") ?? "";
  if (!ts3ClientQuery) {
    ts3ClientQuery = new TS3ClientQuery(apiKey);
    ts3ClientQuery.onNotification = (line: string) => {
      if (!mainWindow || mainWindow.isDestroyed()) return;
      if (line.startsWith("notifytextmessage")) {
        const parsed = parseNotifyTextMessage(line);
        if (parsed) {
          // @ts-ignore
          const ignoredSender: string = settingsStore.get("config.ignoredMessageSender") ?? "";
          const isIgnored =
            ignoredSender.trim() !== "" &&
            parsed.sender.trim().toLowerCase() === ignoredSender.trim().toLowerCase();
          if (!isIgnored) {
            mainWindow.webContents.send("ts3-message-received", { ...parsed, timestamp: new Date().toISOString() });
          }
          return;
        }
      }
      // Anything else unrecognized - log it so we can identify what event
      // name actually carries incoming pokes, if this app ever needs to
      // distinguish them from regular messages.
      console.log("[TS3 notification - unhandled]", line);
    };
  } else {
    ts3ClientQuery.setApiKey(apiKey);
  }
  return ts3ClientQuery;
};

