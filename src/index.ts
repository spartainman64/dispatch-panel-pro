const createMainWindow = (): BrowserWindow => {
  // Create the browser window.
  const mainWindow = new BrowserWindow({
    height: 720,
    width: 1100,
    minHeight: 500,
    minWidth: 700,
    webPreferences: {
      preload: MAIN_WINDOW_PRELOAD_WEBPACK_ENTRY,
    },
  });

  // Remove the default menu bar
  mainWindow.removeMenu();

  // and load the index.html of the app.
  mainWindow.loadURL(MAIN_WINDOW_WEBPACK_ENTRY);

  if (process.env.NODE_ENV === "development") {
    // Open the DevTools.
    mainWindow.webContents.openDevTools();
  }

  return mainWindow;
};

const createEventLogWindow = (): BrowserWindow => {
  const win = new BrowserWindow({
    height: 500,
    width: 800,
    minHeight: 200,
    minWidth: 400,
    title: "Event Log",
    webPreferences: {
      preload: MAIN_WINDOW_PRELOAD_WEBPACK_ENTRY,
    },
  });

  win.removeMenu();
  win.loadURL(`${MAIN_WINDOW_WEBPACK_ENTRY}?view=eventlog`);

  return win;
};

// This method will be called when Electron has finished
// initialization and is ready to create browser windows.
// Some APIs can only be used after this event occurs.
app.on("ready", async () => {
  if (process.env.NODE_ENV === "development") {
    await installExtension(REACT_DEVELOPER_TOOLS, {
      loadExtensionOptions: {
        allowFileAccess: true,
      },
    });
  }

  mainWindow = createMainWindow();

  // @ts-ignore
  if (settingsStore.get("config.stayOnTop") === true) {
    mainWindow.setAlwaysOnTop(true);
  }

  // Removing the default menu bar earlier also removed its built-in
  // "Toggle Developer Tools" shortcut, so it's registered here directly
  // instead, independent of any menu.
  electronLocalShortcut.register(mainWindow, "CmdOrCtrl+Shift+I", () => {
    mainWindow?.webContents.toggleDevTools();
  });

  // Poll for pending 911/311 calls from the main process, not the renderer -
  // Chromium throttles setInterval in unfocused/background windows, which
  // was causing alerts to be delayed until the dispatch panel regained
  // focus. The main process has no such throttling, so it stays reliable
  // even while the dispatcher is tabbed into TeamSpeak.
  let pendingPollInFlight = false;
  setInterval(async () => {
    if (!mainWindow || mainWindow.isDestroyed()) return;
    if (pendingPollInFlight) return; // previous check still running - skip this tick rather than overlap
    pendingPollInFlight = true;
    try {
      const client = getTs3Client();
      // @ts-ignore
      const profiles = settingsStore.get("config.ts3ServerProfiles") ?? [];
      const result = await client.getPendingCounts(profiles);
      mainWindow.webContents.send("ts3-pending-counts-push", result);
    } catch (err) {
      console.error("[TS3 pending-poll] failed:", err);
    } finally {
      pendingPollInFlight = false;
    }
  }, 2000);
});

// Quit when all windows are closed, except on macOS. There, it's common
// for applications and their menu bar to stay active until the user quits
// explicitly with Cmd + Q.
app.on("window-all-closed", () => {
  if (process.platform !== "darwin") {
    app.quit();
  }
});

app.on("activate", () => {
  // On OS X it's common to re-create a window in the app when the
  // dock icon is clicked and there are no other windows open.
  if (BrowserWindow.getAllWindows().length === 0) {
    createMainWindow();
  }
});

const getStore = (
  store: string
): ElectronStore<
  | ConfigSchemaType
  | LocationsSchemaType
  | PostalsSchemaType
  | SettingsSchemaType
> => {
  if (store === "config") {
    return configStore;
  }
  if (store === "locations") {
    return locationsStore;
  }
  if (store === "postals") {
    return postalStore;
  }
  if (store === "settings") {
    return settingsStore;
  }
};

