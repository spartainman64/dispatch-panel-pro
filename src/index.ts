// @ts-ignore
if (settingsStore.get("version") !== SETTINGS_VERSION) {
  // Never destructively clear settings on a version bump - that wipes
  // everything the user configured (API keys, channel IDs, sounds...)
  // back to shipped defaults. Instead, backfill only whatever's actually
  // missing, leaving every existing value untouched. This also runs
  // whenever a new field is added even without a version bump, so a
  // field like a new channel ID setting is never silently absent for
  // someone who already has a settings file from before it existed.
  console.log("[Settings] Schema updated - merging in any new fields, preserving existing values.");
  // @ts-ignore
  const current = (settingsStore.get("config") ?? {}) as Partial<typeof DEFAULT_SETTINGS>;
  const merged = { ...DEFAULT_SETTINGS, ...current };

  // ts3ServerProfiles needs its own per-profile merge (by index) so a
  // brand new per-server field, like civilianChannelId, gets backfilled
  // into each of the user's already-configured server profiles instead
  // of the whole array being replaced wholesale.
  if (Array.isArray(current.ts3ServerProfiles)) {
    merged.ts3ServerProfiles = DEFAULT_SETTINGS.ts3ServerProfiles.map(
      (defaultProfile: Ts3ServerProfile, i: number) => ({
        ...defaultProfile,
        ...(current.ts3ServerProfiles?.[i] ?? {}),
      })
    );
  }

  // @ts-ignore
  settingsStore.set("config", merged);
  // @ts-ignore
  settingsStore.set("version", SETTINGS_VERSION);
}

